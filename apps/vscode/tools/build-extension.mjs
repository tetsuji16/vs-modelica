import { build } from "esbuild";

/**
 * Bundles the extension host entry into a single self-contained file.
 *
 * The extension `require()`s its own workspace packages (`@modelica-studio/*`).
 * At development time those resolve through the pnpm `node_modules` symlinks, but
 * the published VSIX strips `node_modules/**` (see `.vscodeignore`), so bare
 * requires would break at runtime. Bundling inlines every workspace dependency
 * into `dist/extension.js`, which is what makes the package self-contained.
 *
 * The bundle is a CommonJS IIFE: VS Code loads the extension host in a Node
 * context, and we keep `__dirname`/`require` working for the `vscode` module and
 * any native bindings (e.g. `zeromq`) by marking them external.
 */
await build({
  entryPoints: ["src/extension.ts"],
  outfile: "dist/extension.js",
  bundle: true,
  format: "cjs",
  platform: "node",
  target: "node22",
  external: ["vscode", "zeromq"],
  legalComments: "none",
  banner: {
    js: "/* Generated by tools/build-extension.mjs from src/extension.ts. Do not edit. */",
  },
});

console.log("extension host bundled to dist/extension.js");
